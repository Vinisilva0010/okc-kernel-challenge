def prepare(weights):
    """Called once, untimed: binds the five projection weights to the fixed route table (phase-1 shapes)."""
    state = {"w": weights, "h": {}}
    hi = weights["router"].to(torch.bfloat16)
    lo = (weights["router"] - hi.float()).to(torch.bfloat16)
    state["router_hi_t"], state["router_lo_t"] = hi.t().contiguous(), lo.t().contiguous()   # stock-style fallback only
    for name, w in weights.items():
        state["h"][name] = bind_projection(name, w, phase1=True)
    STUDY_HOOK
    torch.cuda.empty_cache()
    return state


def kernel_fn(data, state):
    x = data["x"]
    cfg = data["config"]
    layer, n = cfg["layer"], cfg["n"]
    h = state["h"].get(layer)
    out = h.run(x, n) if h is not None else None
    if out is not None:
        return out
    if layer == "router":
        acc = torch.mm(x, state["router_hi_t"], out_dtype=torch.float32)
        acc += torch.mm(x, state["router_lo_t"], out_dtype=torch.float32)
        return acc
    return F.linear(x, state["w"][layer][:n])
