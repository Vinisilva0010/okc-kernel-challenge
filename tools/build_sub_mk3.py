"""Build the phase-1 file sub_mk3.py (and, with --selfcheck, the check-only measure_mk3_self.py) and the SGLang module from mk_moe/mk_moe.py.

    python3 tools/build_sub_mk3.py            # writes muse_moe_w4a16/sub_mk3.py and serve/sglang/.../muse_mk_moe.py
    python3 tools/build_sub_mk3.py --selfcheck  # also writes muse_moe_w4a16/measure_mk3_self.py (adds MKSELF prints in prepare)
Nothing here is edited by hand downstream: change mk_moe.py or this script and rerun.
"""
import sys

ROOT = "/home/vnspo/okc/"
D = ROOT + "muse_moe_w4a16/"
SG_MODULE = ROOT + "serve/sglang/python/sglang/srt/layers/moe/muse_mk_moe.py"

V1 = open(D + "sub_v1.py").read()
MK = open(D + "mk_moe/mk_moe_v0.py").read()  # frozen v0 module: sub_mk3 stays reproducible


def between(text, start, end):
    i = text.index(start)
    j = text.index(end, i)
    return text[i:j]


head = "# okc: problem=muse_moe_w4a16\n# Generated by tools/build_sub_mk3.py from mk_moe/mk_moe.py (MK MoE on SGLang's Marlin tensors) and sub_v1.py's SGLang-path skeleton (Apache-2.0 where noted).\n"
skeleton = between(V1, "import re\n", "# ============================================================================================ SMALLM BEGIN")
torch_path = between(V1, "def _experts_torch(x, local_ids, state):", "# ============================================================================================ small-M entry")

glue = '''

# ============================================================================================ entry
MK_ENTRY_MAX_M = MK_MAX_TOKENS


def prepare(weights):
    """Called once, untimed: SGLang's Marlin repack (what serving has) plus the MK buffers; nothing else."""
    if not HAVE_SGLANG:
        return {"weights": weights, "norm_w": (weights["post_norm_w"].float() + 1.0).to(torch.bfloat16)}
    state = _prepare_sglang(weights)
    state["mk"] = None
    try:
        bank = state["banks"][(0, 32)]
        device = bank["w13"].device
        mk = MkMoE().build(device).alloc(MK_MAX_TOKENS, MK_TOP_K, MK_HIDDEN, MK_INTER, device)
        state["mk"] = mk
        state["mk_layer"] = mk.bind_layer(bank["w13"], bank["w13_s"], bank["w13_gs"], bank["w2"], bank["w2_s"], bank["w2_gs"])
    except Exception as ex:  # noqa: BLE001  (no nvcc / build error: Marlin serves every M)
        import traceback

        print(f"okc-diag mk unavailable: {type(ex).__name__}: {str(ex)[:300]}\\n" + traceback.format_exc()[-1500:])
        state["mk"] = None
    print(f"okc-diag mk active={state['mk'] is not None}")
    SELFCHECK_HOOK
    torch.cuda.synchronize()
    return state


def kernel_fn(data, state):
    if not HAVE_SGLANG:
        return _kernel_torch(data, state)
    cfg = data["config"]
    x = data["hidden_states"]
    if state["mk"] is not None and x.shape[0] <= MK_ENTRY_MAX_M and cfg["local_count"] == MK_EXPERTS:
        return state["mk"].forward(x, data["topk_ids"], data["topk_weights"], cfg["local_start"], cfg["local_count"], state["mk_layer"],
                                   state["norm_w"], POST_NORM_EPS, True)
    return _kernel_sglang(data, state)
'''

selfcheck = '''
    try:
        if state["mk"] is not None:
            _mk_selfcheck(state)
    except Exception:  # noqa: BLE001
        import traceback

        print("MKSELF failed: " + traceback.format_exc()[-2000:].replace("\\n", "\\nMKSELF "), flush=True)
'''

selfcheck_fn = '''

# ---- CHECK-only self-check (never part of a submitted file): offset 0 vs offset 96 relabelling, and the epilogue's two norm forms in torch.
def _mk_selfcheck(state):
    mk, lw, nw = state["mk"], state["mk_layer"], state["norm_w"]
    dev = nw.device
    g = torch.Generator(device="cpu")
    g.manual_seed(11)
    for m in (1, 8, 32, 33, 128, 256):
        x = (torch.randn(m, MK_HIDDEN, generator=g) * 0.5).to(torch.bfloat16).to(dev)
        ids = torch.stack([torch.randperm(256, generator=g)[:8] for _ in range(m)]).to(torch.int32).to(dev)
        w = torch.softmax(torch.randn(m, 8, generator=g), -1).to(dev)
        o0 = mk.forward(x, ids, w, 0, 32, lw, nw, POST_NORM_EPS, True).clone()
        o1 = mk.forward(x, (ids + 96) % 256, w, 96, 32, lw, nw, POST_NORM_EPS, True).clone()
        torch.cuda.synchronize()
        diff = float((o0.float() - o1.float()).abs().max())
        data = {"hidden_states": x, "topk_ids": ids, "topk_weights": w,
                "config": {"local_start": 0, "local_count": 32, "bs": m}}
        ref = _kernel_sglang(data, state).float()
        rel = float((o0.float() - ref).norm() / ref.norm().clamp(min=1e-9))
        # epilogue in torch from the kernel's own fp32 GEMM2 rows, both norm forms
        b = mk.buf
        rows = b["row_of_slot"][: m * 8].view(m, 8)
        y = b["out2"][rows.clamp(min=0).view(-1)].view(m, 8, MK_HIDDEN)
        live = (rows >= 0).float()
        wf = nw.float()
        outs = {}
        for form in (True, False):
            o = mk.forward(x, ids, w, 0, 32, lw, nw, POST_NORM_EPS, form).clone()
            f = y * wf if form else y
            coef = w * torch.rsqrt(f.pow(2).mean(-1) + POST_NORM_EPS) * live
            r = (y * coef.unsqueeze(-1)).sum(1) * wf
            outs[form] = float((o.float() - r).norm() / r.norm().clamp(min=1e-9))
        print(f"MKSELF M={m} off0==off96 bitwise={bool(torch.equal(o0, o1))} maxabs={diff:.2e} rel_vs_marlin={rel:.2e} epi_wf_true={outs[True]:.1e} epi_wf_false={outs[False]:.1e}", flush=True)
'''


def build(with_self):
    body = head + skeleton + "\n\n" + torch_path + "\n\n# ============================================================================================ MK MoE (mk_moe/mk_moe.py, verbatim)\n" + MK
    g = glue.replace("    SELFCHECK_HOOK\n", selfcheck if with_self else "")
    body += (selfcheck_fn if with_self else "") + g
    return body


open(D + "sub_mk3.py", "w").write(build(False))
# (the SGLang module is written by build_sub_mk4.py)
if "--selfcheck" in sys.argv:
    open(D + "measure_mk3_self.py", "w").write(build(True))
print("ok")
